function 유형찾기(이름) {
  if (!이름) return null;
  const 정규화 = String(이름).replace(/\s+/g, '');
  if (유형[정규화]) return { 이름: 정규화, ...유형[정규화] };
  const 후보 = 유형목록().find((k) => k.includes(정규화) || 정규화.includes(k));
  return 후보 ? { 이름: 후보, ...유형[후보] } : null;
}

