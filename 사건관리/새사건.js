function 실행() {
  const 인수 = 인수읽기(process.argv.slice(2));

  if (인수['도움말'] || 인수['help'] || Object.keys(인수).length === 0) {
    도움말();
    return;
  }

  if (인수['목록']) {
    console.log('사건유형 목록');
    for (const 이름 of 유형목록()) {
      console.log(`  ${이름.padEnd(10, ' ')}  ${유형찾기(이름).설명}`);
    }
    return;
  }

  const 채권자 = 인수['채권자'];
  const 채무자 = 인수['채무자'];
  const 유형인수 = 인수['유형'];

  if (채권자 === undefined || 채권자 === true || 채무자 === undefined || 채무자 === true) {
    console.error('오류: --채권자 와 --채무자 를 모두 지정합니다.');
    process.exitCode = 1;
    return;
  }

  const 유형정보 = 유형찾기(유형인수 === true ? '' : 유형인수);
  if (!유형정보) {
    console.error(`오류: 사건유형을 찾지 못하였습니다. 다음 중에서 지정합니다.\n  ${유형목록().join(', ')}`);
    process.exitCode = 1;
    return;
  }

  const 오늘 = new Date();
  const 연도 = String(오늘.getFullYear());
  const 루트 = 보관루트(인수);
  const 연도폴더 = path.join(루트, 연도);
  const 사건번호 =
    인수['사건번호'] && 인수['사건번호'] !== true
      ? String(인수['사건번호'])
      : 다음사건번호(연도폴더, 연도);

  const 폴더명 = 파일명안전(`${사건번호}_${채권자}_${채무자}_${유형정보.이름}`);
  const 사건폴더 = path.join(연도폴더, 폴더명);

  const 정보 = {
    사건번호,
    접수일: 날짜표기(오늘),
    채권자: String(채권자),
    채무자: String(채무자),
    사건유형: 유형정보.이름,
    법원: 인수['법원'] && 인수['법원'] !== true ? String(인수['법원']) : '',
    법원사건번호: '',
    청구금액: 인수['청구금액'] && 인수['청구금액'] !== true ? String(인수['청구금액']) : '',
    진행상태: '접수',
    담당: 인수['담당'] && 인수['담당'] !== true ? String(인수['담당']) : '신광준',
    폴더명,
  };

  const 만들폴더 = [...기본폴더, ...유형정보.추가폴더];

  if (인수['확인']) {
    console.log(`확인 모드입니다. 아무것도 만들지 아니합니다.\n\n보관 위치: ${사건폴더}\n`);
    for (const f of 만들폴더) console.log(`  + ${f}`);
    console.log('  + 00_사건표지.txt');
    console.log('  + 00_진행점검표.txt');
    console.log(`\n사건대장 등록: ${path.join(루트, '사건대장.csv')}`);
    return;
  }

  if (fs.existsSync(사건폴더)) {
    console.error(`오류: 같은 이름의 사건폴더가 이미 있습니다.\n  ${사건폴더}`);
    process.exitCode = 1;
    return;
  }

  fs.mkdirSync(사건폴더, { recursive: true });
  for (const f of 만들폴더) fs.mkdirSync(path.join(사건폴더, f), { recursive: true });

  fs.writeFileSync(path.join(사건폴더, '00_사건표지.txt'), 사건표지내용(정보, 유형정보), 'utf8');
  fs.writeFileSync(path.join(사건폴더, '00_진행점검표.txt'), 점검표내용(정보, 유형정보), 'utf8');
  const 대장 = 대장등록(루트, 정보);

  console.log(`사건폴더를 만들었습니다.\n`);
  console.log(`  사건번호  ${정보.사건번호}`);
  console.log(`  사건유형  ${정보.사건유형}`);
  console.log(`  위치      ${사건폴더}`);
  console.log(`  폴더      ${만들폴더.length}개`);
  console.log(`  대장      ${대장}`);
}

실행();
