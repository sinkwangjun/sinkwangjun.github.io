'use strict';

/*
 * 새 사건폴더 생성 스크립트
 *
 * 사건 하나를 입력하면 ① 표준 사건폴더 일체, ② 사건표지, ③ 유형별 진행점검표,
 * ④ 사건대장(csv) 등록이 한 번에 이루어집니다.
 *
 * 실행 예)
 *   node 사건관리/새사건.js --채권자 "OO농업협동조합" --채무자 "김OO" --유형 임의경매 --법원 울산지방법원
 *   node 사건관리/새사건.js --목록
 *   node 사건관리/새사건.js --채권자 "OO농협" --채무자 "이OO" --유형 채권압류 --확인
 *
 * 의존성 없음. 사건관리/사건유형.js만 사용합니다.
 */

const fs = require('fs');
const path = require('path');
const { 기본폴더, 공통서류, 유형목록, 유형찾기 } = require('./사건유형');

const 저장소루트 = path.resolve(__dirname, '..');

// --- 인수 처리 ----------------------------------------------------------

function 인수읽기(argv) {
  const 값 = {};
  for (let i = 0; i < argv.length; i += 1) {
    const 토큰 = argv[i];
    if (!토큰.startsWith('--')) continue;
    const 키 = 토큰.slice(2);
    const 다음 = argv[i + 1];
    if (다음 === undefined || 다음.startsWith('--')) {
      값[키] = true;
    } else {
      값[키] = 다음;
      i += 1;
    }
  }
  return 값;
}

// 사건폴더의 기본 보관 위치. 의뢰인의 비밀을 지키기 위하여 저장소 바깥을 기본값으로 둡니다.
function 보관루트(인수) {
  const 지정 = 인수['루트'] || process.env.CASE_ROOT || process.env['사건폴더루트'];
  if (지정 && 지정 !== true) return path.resolve(String(지정));
  return path.resolve(저장소루트, '..', '사건폴더');
}

// --- 유틸 ---------------------------------------------------------------

function 날짜표기(d) {
  return `${d.getFullYear()}. ${d.getMonth() + 1}. ${d.getDate()}.`;
}

function 파일명안전(문자열) {
  return String(문자열)
    .replace(/[\\/:*?"<>|]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function 다음사건번호(연도폴더, 연도) {
  let 최대 = 0;
  if (fs.existsSync(연도폴더)) {
    for (const 이름 of fs.readdirSync(연도폴더)) {
      const m = 이름.match(new RegExp(`^${연도}-(\\d{3})_`));
      if (m) 최대 = Math.max(최대, Number(m[1]));
    }
  }
  return `${연도}-${String(최대 + 1).padStart(3, '0')}`;
}

function csv칸(값) {
  const s = 값 === undefined || 값 === null ? '' : String(값);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

const 대장머리 = [
  '사건번호', '접수일', '채권자', '채무자', '사건유형', '법원',
  '법원사건번호', '청구금액', '진행상태', '담당', '폴더명',
];

function 대장등록(루트, 행) {
  const 대장 = path.join(루트, '사건대장.csv');
  const 줄 = 대장머리.map((k) => csv칸(행[k])).join(',');
  if (!fs.existsSync(대장)) {
    // 엑셀에서 한글이 깨지지 않도록 BOM을 붙입니다.
    fs.writeFileSync(대장, `﻿${대장머리.join(',')}\n${줄}\n`, 'utf8');
  } else {
    const 기존 = fs.readFileSync(대장, 'utf8');
    const 구분 = 기존.endsWith('\n') ? '' : '\n';
    fs.appendFileSync(대장, `${구분}${줄}\n`, 'utf8');
  }
  return 대장;
}

// --- 문서 생성 ----------------------------------------------------------

function 사건표지내용(정보, 유형정보) {
  const 서류 = [...공통서류, ...유형정보.서류].sort((a, b) =>
    a.폴더.localeCompare(b.폴더, 'ko')
  );
  const 서류표 = 서류
    .map((s) => `    [ ] ${s.필수 ? '필수' : '권장'}  ${s.폴더}  /  ${s.문서}`)
    .join('\n');

  return `사 건 표 지

[사건정보]
사건번호: ${정보.사건번호}
접수일: ${정보.접수일}
채권자: ${정보.채권자}
채무자: ${정보.채무자}
사건유형: ${정보.사건유형}
법원: ${정보.법원}
법원사건번호: ${정보['법원사건번호']}
청구금액: ${정보.청구금액}
진행상태: ${정보.진행상태}
담당: ${정보.담당}
폴더명: ${정보.폴더명}
[/사건정보]

※ 위 [사건정보] 구역은 점검.js가 읽어 사건대장을 다시 만드는 자리입니다. 항목의 이름은 그대로 두고 값만 고칩니다.

1. 사건의 개요
   ${유형정보.설명}

2. 당사자
   가. 채권자  ${정보.채권자}
   나. 채무자  ${정보.채무자}
   다. 소유자
   라. 연대보증인
   마. 제3채무자

3. 채권내역
   구분          금액            기산일          이율            근거
   원금
   이자
   지연손해금
   합계
   ※ 원금, 이자, 지연손해금을 구분하고 기산일과 종기, 이율의 근거를 특정합니다. 계산식을 밝혀 검산합니다.

4. 담보와 책임재산
   가. 담보 부동산의 표시
   나. 근저당권  법원(등기소), 접수일자, 접수번호, 등기원인, 등기목적의 순서로 특정합니다
   다. 채권최고액
   라. 선순위 권리관계와 무잉여 위험
   마. 그 밖의 책임재산

5. 절차의 선택과 집행 전략
   가. 집행권원의 확보 방법
   나. 환가 방법
   다. 부수절차의 필요성  사해행위취소, 물상대위, 보전처분, 회생·파산 대응
   라. 예상 회수액과 비용

6. 기한관리
   가. 소멸시효  상행위로 인한 채권은 5년, 판결로 확정된 채권은 10년입니다
       기산일:            만료일:
   나. 제척기간  사해행위취소는 취소원인을 안 날부터 1년, 법률행위가 있은 날부터 5년입니다
       기산일:            만료일:
   다. 배당요구의 종기
   라. 그 밖의 기한

7. 표준 편철 서류 점검표
${서류표}

8. 진행일지
   ${정보.접수일}  사건 접수와 폴더 개설
`;
}

function 점검표내용(정보, 유형정보) {
  const 줄 = 유형정보.점검표
    .map((s, i) => {
      const 번호 = String(i + 1).padStart(2, '0');
      return `${번호}. [ ] ${s.내용}\n      기한: ${s.기한}        처리일:            처리자:`;
    })
    .join('\n\n');

  return `진 행 점 검 표   (${정보.사건유형})

사건번호: ${정보.사건번호}
채권자: ${정보.채권자}
채무자: ${정보.채무자}
개설일: ${정보.접수일}

${줄}

※ 위 점검표는 사건관리/사건유형.js의 정의에서 생성한 것입니다. 사무소의 실무가 바뀌면 그 파일을 고칩니다.
※ 기한은 사무소의 권장 일정이고 법정기간과 법원이 정한 기간은 그때마다 기록에서 다시 확인합니다.
`;
}

